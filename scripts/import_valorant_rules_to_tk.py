def main() -> int:
    written, skipped = 0, 0
    for scope, region, subject, extra, statement, body in ENTRIES:
        tags = ["交易", "游戏:无畏契约", *extra]
        filename = filename_for(scope, region, subject, statement)
        path = os.path.join(repository.TK_DIR, filename)
        if os.path.exists(path):
            print(f"[skip] {filename}")
            skipped += 1
            continue
        repository.write_document(filename, render(statement, body, tags))
        print(f"[write] {filename} | {statement}")
        written += 1
    indexed = repository.request_reindex()
    print(f"\n完成：写入 {written} 条、跳过 {skipped} 条；reindex={'OK' if indexed else 'FAIL'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
